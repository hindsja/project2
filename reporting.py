"""One source for the app's saved numbers and the committee memo."""
import json
from datetime import datetime, timezone
from pathlib import Path
from engine import ROOT, TICKERS

ANNOUNCEMENT = ('AI announcement: Codex (GPT-6) assisted with app implementation, data processing, '
                'validation and drafting. Sources, assumptions and actual checks are documented.\n\n'
                'The submitting analyst is responsible for reviewing the analysis and owning the final '
                'decision. Education, not investment advice.')


def pct(value):
    return f'{value:.2%}'


def allocation(portfolio):
    return ' / '.join(f'{portfolio["weights"][t]:.0%}' for t in TICKERS) if portfolio else 'No feasible portfolio'


def comparison_table(report):
    lines = ['| Portfolio | EWY / QQQM / VOO / FNDX / BIL | Estimated net return | Estimated volatility | One-way turnover | Mandate verdict |',
             '|---|---|---:|---:|---:|---|']
    for p in report['portfolios']:
        if p is None:
            lines.append('| Constrained portfolio | No feasible allocation | — | — | — | FAIL: no feasible grid allocation or unavailable signal |')
        else:
            verdict = 'PASS' if p['passed'] else 'FAIL: ' + '; '.join(p['failed_rules'])
            lines.append(f'| {p["name"]} | {allocation(p)} | {pct(p["net_return"])} | {pct(p["volatility"])} | {pct(p["turnover"])} | {verdict} |')
    return '\n'.join(lines)


def stress_table(report):
    lines = ['| Scenario | Action | EWY / QQQM / VOO / FNDX / BIL | Estimated net return | Estimated volatility |',
             '|---|---|---|---:|---:|']
    for s in report['stresses']:
        p = s['portfolio']
        lines.append(f'| {s["scenario"]} | {s["decision"]} | {allocation(p)} | {pct(p["net_return"]) if p else "—"} | {pct(p["volatility"]) if p else "—"} |')
    return '\n'.join(lines)


def backtest_table(report):
    lines = ['| Process, October 2024–September 2026 | Cumulative return | Annualized compound return | Realized annualized volatility | Maximum monthly drawdown |',
             '|---|---:|---:|---:|---:|']
    for p in report['walk_forward']['results']:
        lines.append(f'| {p["name"]} | {pct(p["total_return"])} | {pct(p["cagr"])} | {pct(p["volatility"])} | {pct(p["max_drawdown"])} |')
    return '\n'.join(lines)


def visible_markdown(report):
    signal = report['signal']
    info = f'{signal["rise_pp"]:+.2f} percentage points; defensive rule {"ON" if signal["defensive"] else "OFF"}' if signal['available'] else signal['reason']
    return f'''# Project 2 — Visible decision output

Generated by the Python engine; AI-assisted historical analysis. Education, not investment advice.

**Decision date: {report['config']['decision_date']}. Run timestamp: {report['run_timestamp_utc']}.**
The decision date is a historical information cutoff, not the download date or today's investment advice.

**Decision: {report['decision']}. {report['decision_line']}**

## Three portfolios under the same mandate

{comparison_table(report)}

Annual return is a historical arithmetic estimate with a 10% equity-return ceiling, plus the stated scenario shift, minus implementation trading costs.
Volatility is estimated from monthly sample covariance annualized by 12. It is not a maximum-loss guarantee.
The starting holding is 60% VOO / 40% BIL. Equal weight requires 60% one-way turnover and fails the 25% transition limit.
Feasible allocations on the 5-percentage-point grid: **{report['feasible_count']}**.

## Point-in-time signal

UNRATE: **{info}**. See [data card](../docs/data-card.md).
Eligible observations used: `{json.dumps(signal['selected_rows'], ensure_ascii=False)}`.
Publication rows excluded as unavailable: `{signal['excluded_future_rows']}`.

## Stress results

{stress_table(report)}

These are AI-assisted validation scenarios, not the student's Locked Changed-Input Record.

## Chronological diagnostic

{backtest_table(report)}

The walk-forward diagnostic always uses 36 months of trailing estimates and annual September rebalances.
Prices then earn the NEXT month's return; holdings drift between rebalances.
It is retrospective, only 24 months long, and not an untouched out-of-sample test.
Baselines execute even when they fail a mandate rule; the JSON records those failures.
Missing signals block new constrained orders; existing holdings remain and warnings are recorded.
This is not evidence that the unemployment signal predicts returns or causes better performance.

## Reproduce

From the project folder: `python app.py --export`.
The complete inputs, checks, stress runs, trade logs, monitoring warnings and hashes are in [results.json](results.json).
'''


def memo_markdown(report):
    p = report['portfolios'][2]
    base = report['portfolios'][1]
    simulated = report['walk_forward']['results'][0]
    benchmark = report['walk_forward']['results'][2]
    without = report['without_signal']['results'][0]
    buffer = pct(p['net_return'] - report['config']['target_return']) if p else 'not applicable'
    estimate_stress = next(s for s in report['stresses'] if s['scenario'].startswith('Equity estimates'))
    risk_stress = next(s for s in report['stresses'] if s['scenario'].startswith('Volatility ceiling'))
    return f'''{ANNOUNCEMENT}

# Investment management decision memo

**Historical cutoff:** {report['config']['decision_date']}. **Prepared:** {report['run_timestamp_utc']}.
Hypothetical seven-year investor; no withdrawals. Final analyst review/sign-off remains pending.

## Committee ask

**{report['decision']}. {report['decision_line']}**

Live allocation range: **0?0%**. Research range, if feasible: **5?10% of a simulated portfolio**.
The weights below apply inside that shadow sleeve, not to actual investor wealth.

## Mandate and decision numbers

The user-approved hypothetical mandate requires a 6.5% estimated annual net return, at most 15% estimated volatility,
60% per fund, at least 10% BIL, no borrowing/shorting, and at most 25% one-way annual turnover.
The starting portfolio and benchmark are 60% VOO / 40% BIL. This is a new client policy, not the Lab 13 Meridian classroom case.

{comparison_table(report)}

The constrained portfolio clears the return target by only **{buffer}**. Its lower risk comes with a larger Treasury-bill allocation.
Equal weight fails the transition-turnover limit despite its attractive estimated return.
Return estimates use historical arithmetic means, a disclosed 10% equity ceiling, and costs on both purchases and sales.
The ceiling is an AI-proposed assumption, not a validated forecast. Volatility is not a maximum-loss guarantee.

## What changes the decision

The equity-estimate stress (minus three percentage points) yields **{estimate_stress['decision']}**;
the 4% risk ceiling yields **{risk_stress['decision']}**. The 60-month window, costs, fund caps and release lag are also tested in the
[full stress table](../outputs/decision-output.md). A weaker equity forecast can require MORE equity to meet a fixed return target;
the risk and turnover limits prevent unlimited compensation.

Only published UNRATE vintages enter the signal. A rise of at least 0.10 percentage point between consecutive knowable months
raises the BIL floor to 40%. Missing consecutive months, observations older than 100 days or no feasible allocation block new orders.
The threshold is experimental, not established predictive evidence.

## Historical reality check

{backtest_table(report)}

The constrained process returned **{pct(simulated['cagr'])}** annualized versus **{pct(benchmark['cagr'])}** for the benchmark.
Without the macro rule it returned **{pct(without['cagr'])}**. This sample provides no demonstrated incremental signal advantage.
The diagnostic is retrospective: 24 monthly returns, two annual decisions, and rules chosen after the period existed.
It is not an untouched holdout. Adjusted prices are revised snapshots; only UNRATE has publication-vintage filtering.

## Monitoring, limitations and reversal

Monitor release availability and weight drift monthly; assess return, risk and turnover at annual rebalances.
Block new orders on invalid data or an infeasible mandate; retain and review existing holdings rather than assume forced liquidation.
Consider live adoption only after at least 12 prospective monthly observations, net performance at least the benchmark,
realized annualized volatility at most 15%, no breach at annual rebalance and committee approval. Even that period is weak statistical evidence.

ETF overlap, covariance regime changes, falling bill yields, taxes, intramonth losses, execution approximation and selection bias remain material risks.
There is no seven-year funding simulation. Baselines trade even when failing a rule; failures and drift warnings are exposed in the logs.

Sources and evidence: [data card](data-card.md), [mandate](mandate.md), [actual results](../outputs/results.json),
[validation and AI use](validation-and-ai-use.md). Human locked-input, partner and video evidence remain pending.
'''


def save_report(report, output_dir=None, snapshot=None):
    report = dict(report, run_timestamp_utc=datetime.now(timezone.utc).isoformat())
    if snapshot:
        folder = ROOT / 'outputs/snapshots' / snapshot
        folder.mkdir(parents=True, exist_ok=False)
    else:
        folder = Path(output_dir or ROOT / 'outputs')
        folder.mkdir(parents=True, exist_ok=True)
    (folder / 'results.json').write_text(json.dumps(report, indent=2, allow_nan=False) + '\n', encoding='utf-8')
    markdown = visible_markdown(report)
    if snapshot:
        markdown = markdown.replace('(../docs/', '(../../../docs/')
    (folder / 'decision-output.md').write_text(markdown, encoding='utf-8')
    if not snapshot and output_dir is None:
        (ROOT / 'docs/decision-memo.md').write_text(memo_markdown(report), encoding='utf-8')
    return folder
